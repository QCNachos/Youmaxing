/**
 * Generate grocery list HTML for PDF
 */
export function generateGroceryPDFContent(data: GroceryExportData): string {
  const itemRows = data.items
    .map(item => `
      <tr>
        <td><span class="checkbox"></span></td>
        <td>${item.name}</td>
        <td>${item.quantity || ''} ${item.unit || ''}</td>
      </tr>
    `)
    .join('');

  return `
    <h1>Grocery List</h1>
    <p class="subtitle">${data.title} - ${data.items.length} items</p>
    <table>
      <thead>
        <tr>
          <th style="width: 40px;"></th>
          <th>Item</th>
          <th style="width: 120px;">Quantity</th>
        </tr>
      </thead>
      <tbody>
        ${itemRows}
      </tbody>
    </table>
  `;
}

/**
 * Generate meal plan HTML for PDF
 */
export function generateMealPlanPDFContent(data: MealPlanExportData): string {
  const dayCards = data.days
    .map(day => `
      <div class="meal-card">
        <div class="meal-day">${day.date}</div>
        ${day.breakfast ? `<div class="meal-slot"><span class="meal-slot-label">Breakfast:</span> ${day.breakfast}</div>` : ''}
        ${day.lunch ? `<div class="meal-slot"><span class="meal-slot-label">Lunch:</span> ${day.lunch}</div>` : ''}
        ${day.dinner ? `<div class="meal-slot"><span class="meal-slot-label">Dinner:</span> ${day.dinner}</div>` : ''}
        ${day.snacks?.length ? `<div class="meal-slot"><span class="meal-slot-label">Snacks:</span> ${day.snacks.join(', ')}</div>` : ''}
      </div>
    `)
    .join('');

  return `
    <h1>Weekly Meal Plan</h1>
    <p class="subtitle">${data.weekStart} - ${data.weekEnd}</p>
    ${dayCards}
  `;
}

/**
 * Generate inventory HTML for PDF
 */
export function generateInventoryPDFContent(data: InventoryExportData): string {
  const itemRows = data.items
    .map(item => `
      <tr>
        <td>${item.name}</td>
        <td>${item.quantity || ''} ${item.unit || ''}</td>
        <td>${(item as any).location || ''}</td>
        <td>${(item as any).expiration_date ? format(new Date((item as any).expiration_date), 'MMM d, yyyy') : ''}</td>
      </tr>
    `)
    .join('');

  return `
    <h1>Inventory</h1>
    <p class="subtitle">${data.title} - ${data.items.length} items</p>
    <table>
      <thead>
        <tr>
          <th>Item</th>
          <th style="width: 100px;">Quantity</th>
          <th style="width: 100px;">Location</th>
          <th style="width: 120px;">Expires</th>
        </tr>
      </thead>
      <tbody>
        ${itemRows}
      </tbody>
    </table>
  `;
}

/**
 * Share content via native share API or clipboard
 */
export async function shareContent(
  title: string,
  text: string,
  url?: string
): Promise<boolean> {
  // Try native share API first (mobile/supported browsers)
  if (navigator.share) {
    try {
      await navigator.share({
        title,
        text,
        url,
      });
      return true;
    } catch (err) {
      // User cancelled or share failed
      if ((err as Error).name !== 'AbortError') {
        console.error('Share failed:', err);
      }
    }
  }

  // Fallback: copy to clipboard
  try {
    const content = url ? `${title}\n\n${text}\n\n${url}` : `${title}\n\n${text}`;
    await navigator.clipboard.writeText(content);
    return true;
  } catch (err) {
    console.error('Clipboard failed:', err);
    return false;
  }
}

/**
 * Generate shareable text for grocery list
 */
export function generateGroceryShareText(items: ExportableItem[]): string {
  return items
    .map(item => `- ${item.name}${item.quantity ? ` (${item.quantity} ${item.unit || ''})` : ''}`)
    .join('\n');
}

/**
 * Generate shareable text for meal plan
 */
export function generateMealPlanShareText(days: MealPlanDay[]): string {
  return days
    .map(day => {
      const meals = [];
      if (day.breakfast) meals.push(`  Breakfast: ${day.breakfast}`);
      if (day.lunch) meals.push(`  Lunch: ${day.lunch}`);
      if (day.dinner) meals.push(`  Dinner: ${day.dinner}`);
      if (day.snacks?.length) meals.push(`  Snacks: ${day.snacks.join(', ')}`);
      return `${day.date}\n${meals.join('\n')}`;
    })
    .join('\n\n');
}

/**
 * Generate shareable text for inventory
 */
export function generateInventoryShareText(items: ExportableItem[]): string {
  return items
    .map(item => `- ${item.name}: ${item.quantity || '?'} ${item.unit || 'items'}`)
    .join('\n');
}

