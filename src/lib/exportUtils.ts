/**
 * Export and Share Utilities for Food Mini-App
 * PDF generation and sharing functionality
 */

import { format } from 'date-fns';

// Types for exportable data
interface ExportableItem {
  name: string;
  quantity?: number;
  unit?: string;
  [key: string]: unknown;
}

interface MealPlanDay {
  date: string;
  breakfast?: string;
  lunch?: string;
  dinner?: string;
  snacks?: string[];
}

interface GroceryExportData {
  title: string;
  items: ExportableItem[];
  generatedAt: string;
}

interface MealPlanExportData {
  title: string;
  weekStart: string;
  weekEnd: string;
  days: MealPlanDay[];
  generatedAt: string;
}

interface InventoryExportData {
  title: string;
  items: ExportableItem[];
  location?: string;
  generatedAt: string;
}

